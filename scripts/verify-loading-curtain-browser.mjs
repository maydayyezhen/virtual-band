import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
const { chromium } = createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://localhost:5173/');
  await page.getByRole('button', { name: /播放歌曲/ }).click();
  await page.waitForFunction(() => window.bandView?.previewState.playing, null, { timeout: 60000 });
  let release;
  const gate = new Promise(resolve => { release = resolve; });
  await page.route('**/queen.mid', async route => { await gate; await route.continue(); });
  await page.getByRole('button', { name: /开始演出/ }).click();
  const curtain = page.locator('.loading-curtain');
  await curtain.waitFor({ state: 'visible' });
  assert.equal(await curtain.evaluate(el => el.matches(':modal')), true);
  const box = await curtain.boundingBox();
  assert.deepEqual(box, { x: 0, y: 0, width: 1440, height: 900 });
  assert.equal(await curtain.evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(8, 19, 33)');
  await page.keyboard.press('Escape');
  assert.equal(await curtain.isVisible(), true);
  await page.keyboard.press('Tab');
  assert.equal(await curtain.evaluate(el => el.contains(document.activeElement)), true);
  const mark = page.locator('.loading-curtain-mark i').first();
  const before = await mark.evaluate(el => getComputedStyle(el).transform);
  await page.waitForTimeout(200);
  assert.notEqual(await mark.evaluate(el => getComputedStyle(el).transform), before);
  await mkdir('exports', { recursive: true });
  await page.screenshot({ path: 'exports/stage-loading.png' });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  assert.equal(await mark.evaluate(el => getComputedStyle(el).animationName), 'none');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  release();
  await curtain.waitFor({ state: 'hidden', timeout: 90000 });
  assert.equal(await page.evaluate(() => window.bandView.instruments.list().length), 7);
  assert.equal(await page.evaluate(() => window.bandView.player.isPlaying), true);
  await page.unroute('**/queen.mid');
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: /选择音乐/ }).click();
  await page.waitForFunction(() => window.bandView.previewState.playing);
  await page.route('**/queen.mid', route => route.fulfill({ status: 503, body: 'Unavailable' }));
  await page.getByRole('button', { name: /开始演出/ }).click();
  await page.locator('.shell-notice').waitFor();
  assert.equal(await curtain.isVisible(), false);
  assert.equal(await page.getByRole('button', { name: /开始演出/ }).isEnabled(), true);
  await page.unroute('**/queen.mid');
  await page.keyboard.press('Escape');
  await page.getByRole('link', { name: /乐器库/ }).click();
  await page.waitForFunction(() => window.virtualBandV2?.instruments.list().length > 0, null, { timeout: 60000 });
  assert.equal(await page.locator('.loading-curtain').isVisible(), false);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ opaqueViewport: true, modalInputBlocking: true, animation: true, reducedMotion: true, readyBeforeReveal: true, failureRecovery: true, library: true, errors }));
} finally { await browser.close(); }
