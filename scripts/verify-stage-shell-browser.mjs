import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
const { chromium } = createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const base = process.env.TEST_URL || 'http://localhost:5173';
  await page.goto(base);
  await page.waitForFunction(() => window.bandView?.session, null, { timeout: 60000 });
  await page.evaluate(() => document.fonts.ready);
  assert.equal(await page.title(), '返场 ENCORE');
  assert.equal(await page.evaluate(() => window.bandView.instruments.list().length), 0);
  assert.equal(await page.locator('.shell-header').count(), 0);
  assert.equal(await page.locator('.shell-footer, .shell-back, .shell-preview').count(), 0);
  await page.mouse.click(1000, 700);
  await page.waitForFunction(() => window.bandView.gameAudio.state.ready && window.bandView.gameAudio.state.menu);
  await page.evaluate(() => {
    const audio = window.bandView.audio;
    const analyser = audio.getContext().createAnalyser();
    window.probe = { analyser, disconnect: audio.connectMixTap(analyser), sounds: [] };
    const original = audio.playBuffer.bind(audio);
    audio.playBuffer = (...args) => { window.probe.sounds.push(args[0].duration); return original(...args); };
  });
  await page.waitForFunction(() => {
    const data = new Float32Array(window.probe.analyser.fftSize); window.probe.analyser.getFloatTimeDomainData(data);
    return data.some(v => Math.abs(v) > .00001);
  });
  const menu = page.getByRole('button', { name: /播放歌曲/ });
  await menu.hover(); await page.waitForTimeout(130);
  await page.mouse.move(1000, 700); await menu.hover();
  assert(await page.evaluate(() => window.probe.sounds.length >= 2), 'Repeated hover plays real decoded UI samples');
  await mkdir('exports', { recursive: true });
  await page.screenshot({ path: 'exports/stage-home.png' });
  await menu.click();
  await page.waitForFunction(() => window.bandView.previewState.id && window.bandView.previewState.playing, null, { timeout: 60000 });
  assert.equal(await page.evaluate(() => window.bandView.gameAudio.state.menu), false);
  assert.equal(await page.locator('.shell-record img').evaluate(el => el.complete && el.naturalWidth > 0 && el.src.endsWith('/bohemian-cover.png')), true);
  assert.equal(await page.locator('.shell-header').count(), 0);
  const record = page.locator('.shell-record');
  const box = await page.locator('.shell-record-zone').boundingBox();
  await page.mouse.move(box.x + box.width * .9, box.y + box.height * .2);
  await page.waitForTimeout(350);
  assert.equal(await record.evaluate(el => el.style.getPropertyValue('--cover-y')), '4.00deg');
  await page.screenshot({ path: 'exports/stage-song-select.png' });
  await page.mouse.move(20, 20);
  assert.equal(await record.evaluate(el => el.style.getPropertyValue('--cover-y')), '0deg');
  await page.waitForFunction(() => Number(document.querySelector('.stage-shell').style.getPropertyValue('--shell-level')) > .01);
  const version = await page.evaluate(() => window.bandView.previewState.version);
  await page.locator('.shell-track').hover();
  assert.equal(await page.evaluate(() => window.bandView.previewState.version), version);
  await page.evaluate(() => window.bandView.playback.seek(61));
  await page.waitForFunction(() => window.bandView.previewState.time >= 36 && window.bandView.previewState.time < 39);
  await page.setViewportSize({ width: 1366, height: 768 });
  const start = await page.getByRole('button', { name: /开始演出/ }).boundingBox();
  assert(start.y >= 0 && start.y + start.height <= 768);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  assert.equal(await record.evaluate(el => getComputedStyle(el).transform), 'none');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.getByRole('button', { name: /开始演出/ }).click();
  await page.waitForFunction(() => document.body.dataset.stageView === 'performance' && window.bandView.player?.isPlaying, null, { timeout: 90000 });
  assert.equal(await page.evaluate(() => window.bandView.instruments.list().length), 7);
  assert.equal(await page.evaluate(() => window.bandView.gameAudio.state.menu), false);
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: /创作工具/ }).click();
  assert.equal(await page.locator('.band-camera').isVisible(), true);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.band-camera').isVisible(), false);
  await page.getByRole('button', { name: /返回主菜单/ }).click();
  await page.waitForFunction(() => document.body.dataset.stageView === 'home' && window.bandView.instruments.list().length === 0 && window.bandView.gameAudio.state.menu);
  assert.equal(await page.evaluate(() => window.bandView.player), null);
  // Leaving selection during fetch must cancel the old preview.
  await page.route('**/queen.mid', async route => { await new Promise(resolve => setTimeout(resolve, 700)); await route.continue().catch(() => {}); });
  await menu.click(); await page.keyboard.press('Escape'); await page.waitForTimeout(1100);
  assert.equal(await page.evaluate(() => window.bandView.previewState.id), null);
  assert.equal(await page.evaluate(() => window.bandView.previewState.playing), false);
  assert.equal(await page.evaluate(() => window.bandView.gameAudio.state.menu), true);
  await page.unroute('**/queen.mid');
  // Failed preview leaves BGM running; hovering the song retries without locking navigation.
  await page.route('**/queen.mid', route => route.fulfill({ status: 503, body: 'Unavailable' }));
  const failed = page.waitForResponse(response => response.url().endsWith('/queen.mid') && response.status() === 503);
  await menu.click(); await failed; await page.waitForTimeout(150);
  assert.equal(await page.evaluate(() => window.bandView.gameAudio.state.menu), true);
  assert.equal(await page.getByRole('button', { name: /开始演出/ }).isEnabled(), true);
  await page.unroute('**/queen.mid'); await page.locator('.shell-track').hover();
  await page.waitForFunction(() => window.bandView.previewState.id && window.bandView.previewState.playing);
  await page.setViewportSize({ width: 1920, height: 1080 });
  await page.screenshot({ path: 'exports/stage-song-select-wide.png' });
  await page.keyboard.press('Escape');
  await page.getByRole('link', { name: /乐器库/ }).click();
  await page.waitForFunction(() => window.gameAudio?.state.ready, null, { timeout: 60000 });
  await page.mouse.click(1100, 100);
  await page.waitForFunction(() => window.gameAudio.state.menu);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ menuAudio: true, repeatedHoverSound: true, automaticPreview: true, previewLoop: true, coverTilt: true, reducedMotion: true, performance: true, cancellationAndRetry: true, libraryAudio: true, errors }));
} finally { await browser.close(); }
