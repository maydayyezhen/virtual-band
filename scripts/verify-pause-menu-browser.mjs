import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const {chromium} = createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({channel:'chrome',headless:true});
try {
 const page = await browser.newPage({viewport:{width:1440,height:900}});
 const errors=[]; page.on('pageerror', e=>errors.push(e.message));
 await page.goto('http://localhost:5173/');
 await page.getByRole('button',{name:/播放歌曲/}).click();
 await page.getByRole('button',{name:/开始演出/}).click();
 await page.waitForFunction(()=>document.body.dataset.stageView==='performance' && window.bandView.player?.isPlaying, null, {timeout:90000});
 await page.locator('.loading-curtain').waitFor({state:'hidden'});
 for (const selector of ['.band-camera','.mb-bar','.game-sound-control','.shell-pause']) assert.equal(await page.locator(selector).isVisible(), false, selector);
 await page.screenshot({path:'exports/stage-clean-performance.png'});
 await page.keyboard.press('Escape');
 await page.waitForFunction(()=>document.body.dataset.stageView==='paused' && !window.bandView.player.isPlaying && window.bandView.gameAudio.state.menu);
 const time=await page.evaluate(()=>window.bandView.player.time);
 const camera=await page.evaluate(()=>window.bandView.camera.output.position.toArray());
 await page.waitForTimeout(500);
 assert(Math.abs(await page.evaluate(()=>window.bandView.player.time)-time)<.04);
 assert.deepEqual(await page.evaluate(()=>window.bandView.camera.output.position.toArray()),camera);
 await page.screenshot({path:'exports/stage-pause-menu.png'});
 await page.keyboard.press('Shift+Tab');
 assert.equal(await page.evaluate(()=>document.activeElement.dataset.action),'home');
 await page.setViewportSize({width:1366,height:768});
 const bounds=await page.getByRole('button',{name:/返回主菜单/}).boundingBox(); assert(bounds.y+bounds.height<768);
 await page.getByRole('button',{name:/创作工具/}).click();
 assert.equal(await page.locator('.band-camera').isVisible(),true);
 await page.keyboard.press('Escape');
 assert.equal(await page.locator('.band-camera').isVisible(),false);
 assert.equal(await page.evaluate(()=>window.bandView.player.isPlaying),false);
 await page.keyboard.press('Escape');
 await page.waitForFunction(()=>document.body.dataset.stageView==='performance' && window.bandView.player.isPlaying);
 assert.equal(await page.evaluate(()=>window.bandView.gameAudio.state.menu),false);
 assert(await page.evaluate(()=>window.bandView.player.time)>=time);
 await page.keyboard.press('Escape');
 await page.getByRole('button',{name:/自由视角/}).click();
 await page.waitForFunction(()=>document.body.dataset.stageView==='performance' && window.bandView.player.isPlaying);
 await page.keyboard.press('Escape');
 await page.getByRole('button',{name:/作品导播/}).click();
 await page.waitForFunction(()=>document.body.dataset.stageView==='performance' && window.bandView.player.isPlaying);
 assert.equal(await page.evaluate(()=>window.bandView.stage.current.kind),'broadcast');
 await page.keyboard.press('Escape');
 await page.getByRole('button',{name:/选择音乐/}).click();
 await page.waitForFunction(()=>window.bandView.previewState.playing && document.body.dataset.stageView==='songs');
 assert.equal(await page.evaluate(()=>window.bandView.player),null);
 assert.equal(await page.evaluate(()=>window.bandView.instruments.list().length),0);
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({cleanStage:true,pauseClock:true,pauseCamera:true,menuMusic:true,resume:true,tools:true,cameraChoices:true,selection:true,keyboard:true,desktopFits:true,errors}));
} finally {await browser.close();}
